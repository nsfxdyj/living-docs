"""Image attachment upload and download routes.

Uploads are validated twice: the declared Content-Type must be an allowed
image type, and the file bytes must carry a matching magic-byte signature,
so a forged Content-Type alone is not enough to sneak in a non-image.
"""

import re
import uuid
from pathlib import Path

from fastapi import APIRouter, Depends, HTTPException, UploadFile, status
from fastapi.responses import FileResponse
from sqlalchemy.orm import Session

from ..config import get_settings
from ..db import get_db
from ..models import Attachment, Document, User
from ..schemas import AttachmentOut
from .deps import get_current_user
from .documents import get_accessible_document

router = APIRouter(tags=["attachments"])

ALLOWED_CONTENT_TYPES = {"image/png", "image/jpeg", "image/gif", "image/webp"}

# Magic-byte prefixes → stored file extension.
_SIGNATURES: list[tuple[bytes, str]] = [
    (b"\x89PNG\r\n\x1a\n", "png"),
    (b"\xff\xd8\xff", "jpg"),
    (b"GIF87a", "gif"),
    (b"GIF89a", "gif"),
]

# Stored filenames are generated by us, but validate anyway on download
# so a crafted URL can never escape the attachments directory.
_FILENAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")


def _sniff_image_type(data: bytes) -> str | None:
    """Return the image extension for the given bytes, or None."""
    for signature, extension in _SIGNATURES:
        if data.startswith(signature):
            return extension
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "webp"
    return None


def _attachments_dir() -> Path:
    return Path(get_settings().attachments_dir)


@router.post(
    "/documents/{document_id}/attachments",
    response_model=AttachmentOut,
    status_code=status.HTTP_201_CREATED,
)
async def upload_attachment(
    document_id: int,
    file: UploadFile,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
) -> AttachmentOut:
    document = get_accessible_document(db, document_id, user)

    content_type = (file.content_type or "").lower()
    data = await file.read()
    if len(data) > get_settings().max_upload_bytes:
        raise HTTPException(
            status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
            detail="File exceeds the maximum upload size",
        )
    extension = _sniff_image_type(data)
    if content_type not in ALLOWED_CONTENT_TYPES or extension is None:
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST,
            detail="Only image uploads are allowed (png, jpg, gif, webp)",
        )

    stored_name = f"{uuid.uuid4().hex}.{extension}"
    directory = _attachments_dir()
    directory.mkdir(parents=True, exist_ok=True)
    (directory / stored_name).write_bytes(data)

    db.add(
        Attachment(
            document_id=document.id, path=stored_name, uploader_id=user.id
        )
    )
    db.commit()
    return AttachmentOut(url=f"/api/attachments/{stored_name}")


@router.get("/attachments/{filename}")
def download_attachment(
    filename: str,
    user: User = Depends(get_current_user),
) -> FileResponse:
    if not _FILENAME_RE.match(filename) or ".." in filename:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Attachment not found")
    path = _attachments_dir() / filename
    if not path.is_file():
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Attachment not found")
    return FileResponse(path)
